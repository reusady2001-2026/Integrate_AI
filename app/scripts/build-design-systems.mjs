#!/usr/bin/env node
// Generates app/src/styles/design-systems.generated.css from the vendored
// tokens.css files under app/design-systems/<name>/tokens.css. The :root
// selector in each upstream file is rewritten to [data-ds="<name>"] so the
// tokens take effect only on the preview surface, not on the app chrome.

import { readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const systemsDir = join(root, "design-systems");
const outFile = join(root, "src", "styles", "design-systems.generated.css");

const systems = (await readdir(systemsDir, { withFileTypes: true }))
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const blocks = [];
for (const name of systems) {
  const css = await readFile(join(systemsDir, name, "tokens.css"), "utf8");
  const scoped = css.replace(/:root\b/g, `[data-ds="${name}"]`);
  blocks.push(`/* --- ${name} --- */\n${scoped.trim()}\n`);
}

const banner = `/* AUTO-GENERATED by app/scripts/build-design-systems.mjs.
 * Do not edit this file by hand. To change a system, edit the upstream
 * tokens.css under app/design-systems/<name>/ and re-run the script.
 * Source: nexu-io/open-design (Apache-2.0). See app/NOTICE.
 */\n\n`;

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, banner + blocks.join("\n"));

console.log(`Wrote ${outFile} (${systems.length} systems: ${systems.join(", ")})`);
